// Regenerates lib/domain/countries.dart (country names and dial codes) and
// zone_countries.dart (timezone -> country) from the system tz database and
// the phone library's metadata.
// Run from the repo root: dart run tool/make_countries.dart /usr/share/zoneinfo
import 'dart:io';

import 'package:phone_numbers_parser/metadata.dart';
import 'package:phone_numbers_parser/phone_numbers_parser.dart';

void main(List<String> args) {
  final dir = args.isEmpty ? '/usr/share/zoneinfo' : args.first;
  final names = <String, String>{};
  for (final line in File('$dir/iso3166.tab').readAsLinesSync()) {
    if (line.startsWith('#') || line.trim().isEmpty) continue;
    final p = line.split('\t');
    names[p[0]] = p[1].trim();
  }
  final iso = {for (final c in IsoCode.values) c.name: c};
  final rows = <(String, String, String)>[];
  for (final e in names.entries) {
    final code = iso[e.key];
    final meta = code == null ? null : metadataByIsoCode[code];
    if (meta == null) continue; // no phone numbering for it (e.g. Antarctica)
    rows.add((e.key, e.value.replaceAll("'", "\\'"), meta.countryCode));
  }
  rows.sort((a, b) => a.$2.compareTo(b.$2));

  final out = StringBuffer('''// GENERATED by tool/make_countries.dart. Do not edit by hand.
// Country names come from the tz database (iso3166.tab); dial codes from the
// phone number library's metadata.

class CountryInfo {
  const CountryInfo(this.iso, this.name, this.dial);

  /// ISO 3166 alpha-2, e.g. PT.
  final String iso;
  final String name;

  /// Calling code without the plus, e.g. 351.
  final String dial;
}

const countries = <CountryInfo>[
''');
  for (final r in rows) {
    out.writeln("  CountryInfo('${r.$1}', '${r.$2}', '${r.$3}'),");
  }
  out.writeln('];\n');
  File('lib/domain/countries.dart').writeAsStringSync(out.toString());

  final known = {for (final r in rows) r.$1};
  final zones = <String, String>{};
  for (final line in File('$dir/zone.tab').readAsLinesSync()) {
    if (line.startsWith('#') || line.trim().isEmpty) continue;
    final p = line.split('\t');
    if (known.contains(p[0])) zones[p[2]] = p[0];
  }
  final z = StringBuffer('''// GENERATED by tool/make_countries.dart. Do not edit by hand.
// IANA timezone name -> ISO 3166 country, from the tz database's zone.tab.

const zoneCountries = <String, String>{
''');
  final keys = zones.keys.toList()..sort();
  for (final k in keys) {
    z.writeln("  '$k': '${zones[k]}',");
  }
  z.writeln('};');
  File('lib/domain/zone_countries.dart').writeAsStringSync(z.toString());
  stdout.writeln('${rows.length} countries, ${zones.length} zones');
}
