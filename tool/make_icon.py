"""Draws the temporary Lately icon (the "orbit" concept): a white ring with a dot
orbiting a center point, on a teal rounded square. Writes the Android launcher
icons (adaptive, themed and legacy) and a 512 px preview.

Run from the repo root:  python3 tool/make_icon.py
Needs Pillow. The final artwork replaces this later; keep the file names.
"""
import math
import os

from PIL import Image, ImageDraw

TEAL = (46, 111, 94, 255)  # the app's accent colour
WHITE = (255, 255, 255, 255)
SS = 4  # supersampling


def orbit_mask(size, scale):
    """Alpha mask of the ring, the orbiting dot and the centre point.
    `scale` is the ring radius as a fraction of `size`."""
    n = size * SS
    m = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(m)
    c = n / 2
    r = scale * n
    stroke = 0.17 * r
    # ring
    d.ellipse([c - r, c - r, c + r, c + r], fill=255)
    d.ellipse([c - r + stroke, c - r + stroke, c + r - stroke, c + r - stroke], fill=0)
    # centre point
    cr = 0.17 * r
    d.ellipse([c - cr, c - cr, c + cr, c + cr], fill=255)
    # the orbiting dot, up and to the right, sitting on the ring
    a = math.radians(-42)
    ox, oy = c + r * math.cos(a), c + r * math.sin(a)
    dr = 0.30 * r
    d.ellipse([ox - dr, oy - dr, ox + dr, oy + dr], fill=255)
    return m.resize((size, size), Image.LANCZOS)


def foreground(size):
    """Adaptive-icon layer: white shapes on transparent, inside the safe zone
    (the middle 66/108 of the canvas)."""
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    img.paste(Image.new("RGBA", (size, size), WHITE), (0, 0), orbit_mask(size, 0.205))
    return img


def legacy(size):
    """Pre-Android 8 icon: the teal rounded square with the orbit on it."""
    n = size * SS
    sq = Image.new("L", (n, n), 0)
    ImageDraw.Draw(sq).rounded_rectangle([0, 0, n - 1, n - 1], radius=int(0.22 * n), fill=255)
    sq = sq.resize((size, size), Image.LANCZOS)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    img.paste(Image.new("RGBA", (size, size), TEAL), (0, 0), sq)
    img.paste(Image.new("RGBA", (size, size), WHITE), (0, 0), orbit_mask(size, 0.30))
    return img


def main():
    res = "android/app/src/main/res"
    for name, fg, lg in [("mdpi", 108, 48), ("hdpi", 162, 72), ("xhdpi", 216, 96),
                         ("xxhdpi", 324, 144), ("xxxhdpi", 432, 192)]:
        os.makedirs(f"{res}/mipmap-{name}", exist_ok=True)
        foreground(fg).save(f"{res}/mipmap-{name}/ic_launcher_foreground.png")
        legacy(lg).save(f"{res}/mipmap-{name}/ic_launcher.png")
    os.makedirs(f"{res}/mipmap-anydpi-v26", exist_ok=True)
    with open(f"{res}/mipmap-anydpi-v26/ic_launcher.xml", "w") as f:
        f.write('''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/make_icon.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
''')
    with open(f"{res}/values/ic_launcher_background.xml", "w") as f:
        f.write('''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/make_icon.py -->
<resources>
    <color name="ic_launcher_background">#2E6F5E</color>
</resources>
''')
    os.makedirs("docs/icon", exist_ok=True)
    legacy(512).save("docs/icon/lately-icon-512.png")


if __name__ == "__main__":
    main()
